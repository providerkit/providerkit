import assert from "node:assert/strict";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const site = fileURLToPath(new URL("..", import.meta.url));
const manifest = `${site}/scripts/legacy-reference-routes.json`;

// Capture once from the old build, not from guessed TypeDoc symbol names.
if (process.argv.includes("--capture")) {
  assert(!existsSync(manifest), "The baseline route capture already exists.");
  const routes = readdirSync(`${site}/dist/reference`, { recursive: true })
    .filter((path): path is string => typeof path === "string" && path.endsWith("/index.html"))
    .map((path) => `/reference/${path.slice(0, -"index.html".length)}`)
    .sort();
  assert(routes.length > 0, "Build the original site before capturing its routes.");
  writeFileSync(manifest, `${JSON.stringify(routes, null, 2)}\n`);
}

const routes: string[] = JSON.parse(readFileSync(manifest, "utf8"));
const redirects = routes.flatMap((old) => {
  assert(old.startsWith("/reference/") && old.endsWith("/"));
  const target = old.replace("/reference/", "/reference/core/");
  return [
    [old, target],
    [old.slice(0, -1), target],
    [`${old.slice(0, -1)}.md`, `${target.slice(0, -1)}.md`],
  ];
});
assert.equal(new Set(redirects.map(([old]) => old)).size, redirects.length);
assert(redirects.length <= 2000, "Cloudflare Pages allows 2,000 static redirects.");

if (process.argv.includes("--check")) {
  for (const [, target] of redirects) {
    const file = target!.endsWith("/") ? `${target}index.html` : target;
    assert(existsSync(`${site}/dist${file}`), `Missing redirect target: ${target}`);
  }
  assert.equal(readFileSync(`${site}/dist/_redirects`, "utf8"), render());
  console.log(`Checked ${routes.length} legacy reference routes, including Markdown.`);
} else {
  writeFileSync(`${site}/public/_redirects`, render());
}

function render() {
  return [
    "# Generated by scripts/reference-routes.ts from the captured baseline routes.",
    ...redirects.map(([old, target]) => `${old} ${target} 301`),
    "",
  ].join("\n");
}
